function parseList(txt){
  const seen = new Set(), out = [];
  txt.split(/[\s,;]+/).map(x => x.replace(/^["']|["']$/g, "").trim().toUpperCase()).filter(Boolean).forEach(tok => {
    let sym = tok;
    if (/^ENSG\d+/.test(tok) && MDSLE.ensg[tok.split(".")[0]]) sym = MDSLE.ensg[tok.split(".")[0]];
    if (seen.has(sym)) return; seen.add(sym); out.push(sym);
  });
  return out;
}
function runAnalyze(){
  const out = document.getElementById("anout");
  const upAll = parseList(document.getElementById("up").value);
  const dnAll = parseList(document.getElementById("dn").value);
  if (!upAll.length && !dnAll.length){ out.innerHTML = "<p>" + T("empty") + "</p>"; return; }
  const N = 20000, S = MDSLE.sets;
  const setsDef = [["core_up", S.core_up, "set_coreup"], ["core_down", S.core_down, "set_coredn"],
                   ["core65", S.core65, "set_core65"],
                   ["sh_up", S.shared123.filter(g => byGene[g].direction === "up"), "set_shup"],
                   ["sh_dn", S.shared123.filter(g => byGene[g].direction === "down"), "set_shdn"],
                   ["sh123", S.shared123, "set_sh123"]];
  let h = `<h3>${T("h_enrich")}</h3><table><tr><th></th><th>${T("th_set")}</th><th>${T("th_k")}</th><th>${T("th_fold")}</th><th>p</th></tr>`;
  [["↑", upAll], ["↓", dnAll]].forEach(([arrow, list]) => {
    if (!list.length) return;
    setsDef.forEach(([key, members, lab]) => {
      const setS = new Set(members), k = list.filter(g => setS.has(g)).length;
      const p = hyperP(N, members.length, list.length, k);
      const fold = list.length && members.length ? (k / list.length) / (members.length / N) : 0;
      h += `<tr><td>${arrow}</td><td>${T(lab)}</td><td>${k} / ${list.length} (set ${members.length})</td><td>${fold.toFixed(2)}×</td><td>${pFmt(p)}</td></tr>`;
    });
  });
  h += "</table>";
  const conc = (list, dir) => {
    const inside = list.filter(g => byGene[g]);
    const k = inside.filter(g => byGene[g].direction === dir).length;
    return { k, n: inside.length, p: binomP(k, inside.length) };
  };
  const cu = conc(upAll, "up"), cd = conc(dnAll, "down");
  h += `<h3>${T("h_conc")}</h3>`;
  if (cu.n) h += `<p>▲ <b>${cu.k} / ${cu.n}</b> (${(100 * cu.k / cu.n).toFixed(0)}%) ${T("conc_up")}; binomial p = ${pFmt(cu.p)}</p>`;
  if (cd.n) h += `<p>▼ <b>${cd.k} / ${cd.n}</b> (${(100 * cd.k / cd.n).toFixed(0)}%) ${T("conc_dn")}; binomial p = ${pFmt(cd.p)}</p>`;
  if (!cu.n && !cd.n) h += `<p class="small">0 ${T("matched")}; ${upAll.length + dnAll.length} ${T("unmatched")}.</p>`;
  const matched = [...new Set([...upAll, ...dnAll])].filter(g => byGene[g]);
  if (matched.length){
    h += `<h3>${T("h_genes")}</h3><table><tr><th>${T("th_gene")}</th><th>${T("th_yours")}</th><th>${T("th_prog")}</th><th>${T("th_tier")}</th><th>${T("th_md")}</th><th>${T("th_sle")}</th></tr>`;
    matched.forEach(g => {
      const r = byGene[g], yours = upAll.includes(g) ? (dnAll.includes(g) ? "↑↓" : "↑") : "↓";
      h += `<tr><td><b>${g}</b></td><td>${yours}</td><td>${r.direction === "up" ? "▲" : "▼"}</td><td>${r.tier}</td><td>${f2(r.MD_logFC)}</td><td>${f2(r.SLE_logFC)}</td></tr>`;
    });
    h += "</table>";
  }
  out.innerHTML = h;
}
