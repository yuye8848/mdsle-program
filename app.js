function humanize(v){
  if (v === true) return LANG === "zh" ? "是" : "Yes";
  if (v === false) return LANG === "zh" ? "否" : "No";
  if (typeof v === "string" && ENUM_LABELS[v]) return ENUM_LABELS[v][LANG] || ENUM_LABELS[v].en;
  return v;
}
function kvHTML(r, labels){
  labels = labels || FIELD_LABELS;
  let h = '<div class="kv">';
  labels.forEach(([k, lab]) => {
    let v = r[k];
    if (k === "sc_concordant_celltypes" && v !== null && v !== undefined)
      v = v + " / " + r.sc_celltypes_tested;
    if (typeof v === "number") v = (Math.abs(v) < 0.001 && v !== 0) ? fSig(v) : f2(v);
    if (v === null || v === undefined || v === "") v = "—"; else v = humanize(v);
    h += `<div><b>${lab}</b>${v}</div>`;
  });
  return h + "</div>";
}
function lookup(){
  const q = document.getElementById("gene").value.trim().toUpperCase();
  const out = document.getElementById("geneout");
  if (!q) { out.innerHTML = ""; return; }
  const r = byGene[q], t = byTarget[q];
  let h = "";
  if (r){
    h += `<h3>${q} <span class="badge ${r.direction === "up" ? "b-up" : "b-dn"}">${r.direction === "up" ? "▲ up" : "▼ down"}</span>` +
         (r.in_core65 ? `<span class="badge">core-65</span>` : "") + (r.in_top13 ? `<span class="badge">top-13</span>` : "") +
         `<span class="badge">${T("in_program")}</span></h3>` + kvHTML(r);
  }
  if (t){
    h += `<h3>${q} — ${T("as_target")}</h3>` + kvHTML(t, TARGET_LABELS);
  }
  if (!r && !t) h = `<p><b>${q}</b> ${T("not_member")}</p><p class="small">${T("not_found")}</p>`;
  else if (r && !t) h += "";
  else if (!r && t) h = `<p class="small"><b>${q}</b>: ${T("not_in_program")} — ${T("as_target")}.</p>` + h;
  out.innerHTML = h;
}
function renderMap(){
  const tb = document.getElementById("maptbody"); if (!tb || !window.MDSLE) return;
  const maxS = 2;
  tb.innerHTML = MDSLE.map.map(r => {
    const w = Math.max(0, r.S) / maxS * 100;
    return `<tr><td>${r.label}</td><td>${r.n_case} / ${r.n_ctrl}</td><td>${f2(r.delta_up)}</td><td>${f2(r.delta_down)}</td>` +
           `<td><b>${f2(r.S)}</b> <div class="bar" style="width:${w}%"></div></td><td>${pFmt(r.perm_p)}</td></tr>`;
  }).join("");
}

