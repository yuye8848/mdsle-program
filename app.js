/* ---------- numeric helpers (same Lanczos lgamma approach as sister atlases) ---------- */
const LG=[0.99999999999980993,676.5203681218851,-1259.1392167224028,771.32342877765313,-176.61502916214059,12.507343278686905,-0.13857109526572012,9.9843695780195716e-6,1.5056327351493116e-7];
function lgamma(z){ if(z<0.5) return Math.log(Math.PI/Math.sin(Math.PI*z))-lgamma(1-z); z-=1; let x=LG[0]; for(let i=1;i<9;i++) x+=LG[i]/(z+i); const t=z+7.5; return 0.5*Math.log(2*Math.PI)+(z+0.5)*Math.log(t)-t+Math.log(x); }
function logC(n,k){ return (k<0||k>n)?-Infinity:lgamma(n+1)-lgamma(k+1)-lgamma(n-k+1); }
function hyperP(N,K,n,k){ if(k<=0) return 1; const mx=Math.min(K,n); let s=0; for(let i=k;i<=mx;i++) s+=Math.exp(logC(K,i)+logC(N-K,n-i)-logC(N,n)); return Math.min(1,s); }
function binomP(k,n){ if(n===0) return null; let s=0; for(let i=k;i<=n;i++) s+=Math.exp(logC(n,i)-n*Math.log(2)); return Math.min(1,s); }
function pFmt(p){ if(p===null||p===undefined) return "—"; if(p<0.001) return p.toExponential(1); return p.toFixed(3); }
function f2(x){ return (x===null||x===undefined||Number.isNaN(x)) ? "—" : Number(x).toFixed(3); }
function fSig(x){ return (x===null||x===undefined||Number.isNaN(x)) ? "—" : Number(x).toExponential(1); }

